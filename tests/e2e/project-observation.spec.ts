import { test, expect, type Locator } from '@playwright/test';
import fs from 'node:fs';
import { projectObservationFixture } from '../fixtures/project-observation.mjs';
test.skip(process.env.LIOOPS_OBSERVER_STATIC !== '1', 'Requires the separate public export.');
test('D observes approved projects and providers, selected logs, honest quota and PC-local sharing changes', async ({ page, context, baseURL }) => {
  test.setTimeout(420000);
  const fixture = await projectObservationFixture(new URL(baseURL!).origin), pc = await context.newPage(), errors: string[] = [], api: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/^\/(?:api|stream|event|hook)(?:\/|$)/.test(new URL(request.url()).pathname)) api.push(request.url()); });
  await page.addInitScript(() => { localStorage.setItem('office-tips', 'seen'); localStorage.setItem('office-quality', 'low'); localStorage.setItem('office-layout', 'cozy'); });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const started = Date.now(), progress = (phase: string) => console.info(`D browser: ${phase} (${Date.now() - started}ms)`);
  try {
    await page.goto(fixture.invite!); await page.getByRole('button', { name: 'Yêu cầu ghép' }).click();
    await expect(page.locator('.cs-fingerprint')).toHaveText(/^[A-Za-z0-9_-]{43}$/);
    await pc.goto(fixture.controlURL); await expect(pc.locator('#fingerprint')).toHaveText(await page.locator('.cs-fingerprint').innerText());
    await expect(pc.locator('#projects')).toContainText('green-project'); await pc.locator('#approve').click();
    await page.bringToFront();
    await expect(page.locator('#rail-list .ri')).toHaveCount(2, { timeout: 90000 });
    progress('paired');
    await expect(page.locator('#btn-give-work')).toBeHidden();
    const codexRow = page.locator('#rail-list .ri').filter({ has: page.locator('[data-agent="codex"]') });
    const claudeRow = page.locator('#rail-list .ri').filter({ has: page.locator('[data-agent="claude"]') });
    const rows = page.locator('#rail-list .ri');
    const openRow = async (row: Locator) => { if (await row.getAttribute('aria-current') !== 'true') await row.click({ noWaitAfter: true }); };
    const openOverview = async () => { await expect(page.locator('#remote-observation')).toBeVisible(); if (await page.locator('#remote-observation').getAttribute('open') === null) await page.locator('#remote-observation summary').click(); };
    await openRow(codexRow); await expect(page.locator('#ds-body')).toContainText('PRIVATE-D-CODEX-ANSWER');
    await expect(page.locator('#ds-codex-usage')).toContainText('90%');
    await fixture.append(); await expect(page.locator('#ds-body')).toContainText('PRIVATE-D-LIVE-UPDATE');
    await openRow(claudeRow); await expect(page.locator('#ds-body')).toContainText('PRIVATE-D-CLAUDE-ANSWER'); await expect(page.locator('#ds-ctx')).toHaveText('–');
    await openOverview();
    await expect(page.locator('[data-quota-state="fresh"]')).toContainText('75%');
    await expect(page.locator('#remote-observation')).toContainText('PC chưa cho phép chia sẻ');
    await fixture.addOldSession(); await expect(rows).toHaveCount(3, { timeout: 90000 }); await expect(page.locator('[data-quota-state="stale"]')).toContainText('Số liệu cũ');
    progress('both providers, live log and stale quota verified');
    await pc.locator('#allow-content').uncheck(); await pc.locator('#allow-quota').uncheck(); await pc.locator('#allow-metrics').check(); await pc.locator('#apply').click();
    await page.bringToFront();
    await expect.poll(() => fixture.connector.state.revision).toBe(2);
    await expect(page.locator('#remote-observation[data-revision="2"]')).toBeVisible({ timeout: 90000 });
    await expect(rows).toHaveCount(3); await expect(page.locator('#ds-body')).not.toContainText('PRIVATE-D');
    await openRow(rows.first()); await expect(page.locator('#ds-body')).toContainText('PC đang tắt quyền');
    await openOverview();
    await expect(page.locator('[data-metric="memory"]')).toContainText('GB'); await expect(page.locator('[data-quota-state]')).toHaveCount(0);
    await page.screenshot({ path: test.info().outputPath('d-permissions.png') });
    progress('content and quota revoked, metrics allowed');
    await pc.locator('#allow-content').check(); await pc.locator('#apply').click(); await expect.poll(() => fixture.connector.state.revision).toBe(3);
    await page.bringToFront();
    await expect(page.locator('#remote-observation[data-revision="3"]')).toBeVisible({ timeout: 90000 });
    await expect(page.locator('.remote-status')).toContainText('Đã kết nối'); await expect(rows).toHaveCount(3);
    await openRow(rows.first()); await expect(page.locator('#ds-body')).toContainText('PRIVATE-D');
    progress('content restored');
    await page.reload(); await expect(rows).toHaveCount(3, { timeout: 90000 });
    await expect(page.locator('#pending')).toHaveCount(0); await expect(pc.locator('#pending')).toBeHidden();
    progress('trusted D pairing resumed after reload');
    await pc.locator('#revoke').click(); await page.bringToFront(); await expect(rows).toHaveCount(0);
    for (const body of fixture.wire) for (const secret of ['PRIVATE-D', 'green-project', 'NEVER-SHARE']) expect(body).not.toContain(secret);
    expect(api).toEqual([]); expect(errors).toEqual([]);
  } catch (error) {
    await page.screenshot({ path: test.info().outputPath('d-failure.png'), timeout: 10000 }).catch(() => {});
    const diagnostic = JSON.stringify({ state: fixture.connector.state, errors, api, wireCount: fixture.wire.length, delivery: fixture.delivery });
    fs.writeFileSync(test.info().outputPath('d-state.json'), diagnostic);
    await test.info().attach('d-state', { contentType: 'application/json', body: Buffer.from(diagnostic) });
    throw error;
  } finally {
    await context.setOffline(false).catch(() => {});
    await Promise.allSettled([page.close(), pc.close()]);
    await fixture.close();
  }
});
