import { test, expect } from '@playwright/test';
test.skip(process.env.LIOOPS_OBSERVER_STATIC !== '1', 'This flow requires the separate public static export.');
test('the public homepage keeps the original office and starts with connection setup', async ({ page }) => {
  test.setTimeout(120000);
  const api: string[] = [], errors: string[] = [];
  page.on('request', r => { if (/(?:^|\/)(?:api|stream|event|hook)(?:\/|$)/.test(new URL(r.url()).pathname)) api.push(r.url()); });
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => { localStorage.setItem('office-tips', 'seen'); localStorage.setItem('office-quality', 'low'); localStorage.setItem('office-layout', 'cozy'); });
  await page.goto('/vi/');
  await expect(page.locator('#app .topbar')).toBeVisible();
  await expect(page.locator('.ob-app')).toHaveCount(0);
  const dialog = page.getByRole('dialog', { name: 'Kết nối một lần. Dùng văn phòng như cũ.' });
  await expect(dialog).toBeVisible();
  await expect(page.locator('#stage canvas')).toHaveCount(0);
  await page.evaluate(() => document.dispatchEvent(new Event('lioops:office-open')));
  await expect(page.locator('#stage canvas')).toHaveCount(0);
  await expect(dialog.getByRole('button', { name: 'Tải bộ kết nối' })).toBeDisabled();
  await expect(dialog).toContainText('Bộ cài tự động chưa có');
  await expect(dialog.getByRole('link', { name: /Đã có LioOps/ })).toHaveAttribute('href', 'http://127.0.0.1:4310/?lang=vi');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await dialog.evaluate(e => e.scrollWidth <= e.clientWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('connection-setup-phone.png') });
  expect(api).toEqual([]);
  await page.setViewportSize({ width: 1440, height: 900 });
  await dialog.getByRole('link', { name: 'Xem văn phòng mẫu' }).click();
  await expect(page.locator('.cs-dialog')).toHaveCount(0);
  await expect(page.locator('#stage canvas')).toBeVisible({ timeout: 90000 });
  await expect(page.locator('#demo-chip')).toBeVisible();
  await expect(page.locator('#rail-list .ri').first()).toBeVisible();
  await page.locator('#btn-look').click();
  await page.locator('#st-connection-setup').click();
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Đóng cấu hình' }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('#stage canvas')).toBeVisible();
  expect(api).toEqual([]);
  expect(errors).toEqual([]);
});

test('the English public export cannot select local APIs through a URL or a setup event', async ({ page }) => {
  const api: string[] = [], errors: string[] = [];
  page.on('request', r => { if (/(?:^|\/)(?:api|stream|event|hook)(?:\/|$)/.test(new URL(r.url()).pathname)) api.push(r.url()); });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/?source=local-http&connected=true');
  await expect(page.locator('.cs-dialog')).toBeVisible();
  await page.evaluate(() => document.dispatchEvent(new Event('lioops:office-open')));
  await expect(page.locator('#stage canvas')).toHaveCount(0);
  await expect(page.locator('#rail-list .ri')).toHaveCount(0);
  await expect(page.locator('#demo-chip')).toBeHidden();
  expect(api).toEqual([]); expect(errors).toEqual([]);
});
